#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { gradlePackages } from './gradle-licenses.mjs';

const LOCK_PATH = 'web/package-lock.json';
const OUTPUT_PATH = 'docs/third-party-licenses.md';
const CHECK = process.argv.includes('--check');

/**
 * Permissive licences Monosai's distribution allows for production
 * dependencies. Anything else — including copyleft licences that would
 * require this application to be redistributed under matching terms — fails
 * the check rather than being silently included.
 */
const ALLOWED_LICENSES = new Set([
  'MIT',
  'Apache-2.0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'CC0-1.0',
]);

function packageNameFromPath(path) {
  const segments = path.split('node_modules/');
  return segments[segments.length - 1];
}

/**
 * Resolves production dependencies from `package-lock.json`'s installed
 * package graph, not from `package.json`'s direct `dependencies` alone: a
 * transitive dependency ships in the same bundle and is exactly as much a
 * distribution obligation as a direct one. `dev: true` entries are excluded
 * because npm already computed, for the whole graph, which packages are
 * reachable only from devDependencies.
 */
function productionPackages(lock) {
  const packages = [];
  for (const [path, meta] of Object.entries(lock.packages ?? {})) {
    if (path === '' || meta.dev === true) {
      continue;
    }
    packages.push({
      name: packageNameFromPath(path),
      version: meta.version ?? 'unknown',
      license: typeof meta.license === 'string' ? meta.license : null,
      resolved: meta.resolved ?? null,
    });
  }
  return packages.sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

function renderDoc(packages) {
  const lines = [
    '# Third-party licences',
    '',
    'Production dependencies bundled into the Monosai application, generated by',
    '`npm run licenses:build` from `web/package-lock.json` and the resolved Gradle',
    'runtime graph in `android-bridge/runtime-dependencies.json`. Do not edit by hand — run',
    'the script after any dependency change and commit the result.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
  ];
  for (const pkg of packages) {
    lines.push(`| ${pkg.name} | ${pkg.version} | ${pkg.license ?? '(unknown)'} |`);
  }
  return `${lines.join('\n')}\n`;
}

async function main() {
  const lock = JSON.parse(await readFile(LOCK_PATH, 'utf8'));
  const reportIndex = process.argv.indexOf('--gradle-report');
  if (reportIndex !== -1 && process.argv[reportIndex + 1] === undefined)
    throw new Error('Missing Gradle report path');
  const packages = [
    ...productionPackages(lock),
    ...(await gradlePackages(reportIndex === -1 ? undefined : process.argv[reportIndex + 1])),
  ];

  const failures = [];
  for (const pkg of packages) {
    if (pkg.license === null) {
      failures.push(`${pkg.name}@${pkg.version} has no licence recorded in package-lock.json`);
      continue;
    }
    if (!ALLOWED_LICENSES.has(pkg.license)) {
      failures.push(`${pkg.name}@${pkg.version} uses disallowed licence "${pkg.license}"`);
    }
  }

  if (failures.length > 0) {
    process.stderr.write(`licence check failed:\n- ${failures.join('\n- ')}\n`);
    process.exitCode = 1;
    return;
  }

  const rendered = renderDoc(packages);
  if (CHECK) {
    const committed = await readFile(OUTPUT_PATH, 'utf8').catch(() => null);
    if (committed !== rendered) {
      process.stderr.write(
        `${OUTPUT_PATH} is out of date; run npm run licenses:build and commit the result\n`,
      );
      process.exitCode = 1;
      return;
    }
    process.stdout.write(
      `${String(packages.length)} production dependencies, all permissively licensed\n`,
    );
    return;
  }

  await writeFile(OUTPUT_PATH, rendered, 'utf8');
  process.stdout.write(`wrote ${OUTPUT_PATH} (${String(packages.length)} packages)\n`);
}

await main();
