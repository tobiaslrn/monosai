import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { citedRules } from './design-check.mjs';
import { checkPage, render } from './design-checks-doc.mjs';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

test('finds every way a check source cites a rule', () => {
  const source = [
    "errors.push(`x. ${cite('R47')}`);",
    "restriction(\n    'R15',",
    "'uses a raw <details>. Fix: use mn-disclosure. (R2 in docs/design/rules.md)',",
    'export const RULES = {\n  R35:\n    `sets a size`,',
    "  [/^border-radius$/, ['a radius role token (--radius-*)', 'R38']],",
    'const pattern = /cite(rule)/;',
  ].join('\n');
  assert.deepEqual(citedRules(source), ['R47', 'R15', 'R2', 'R35', 'R38']);
});

test('docs/design/checks.md is what design-checks.json generates', async () => {
  assert.deepEqual(await checkPage(webRoot), []);
});

test('the checks page lists checked and retired rules in number order', () => {
  const page = render([
    { rule: 'R15', says: 'A row | holds nothing.', check: 'design lint', status: 'checked' },
    { rule: 'R2', says: 'Compose.', check: 'composition freeze', status: 'checked' },
    { rule: 'R30', says: 'No pill.', check: 'now covered by R15', status: 'retired' },
  ]);
  assert.match(page, /^<!-- Generated by `node web\/scripts\/design-checks-doc\.mjs`/);
  assert.ok(page.indexOf('| R2 |') < page.indexOf('| R15 |'));
  assert.match(page, /\| R15 \| A row \\\| holds nothing\. \| design lint \|/);
  assert.match(page, /## Retired[\s\S]*\| R30 \| No pill\. \| now covered by R15 \|/);
  assert.doesNotMatch(render([]), /## Retired/);
});
