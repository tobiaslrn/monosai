// Writes docs/design/checks.md from scripts/design-checks.json: which design
// rules a check enforces, and which rules are retired and what covers them now.
// `--check` fails when the page is not what the list generates.
//
//   node scripts/design-checks-doc.mjs           writes the page
//   node scripts/design-checks-doc.mjs --check   fails if it is stale

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cite } from './design-lint-rules.mjs';

export const PAGE = 'docs/design/checks.md';
export const COMMAND = 'node web/scripts/design-checks-doc.mjs';

const byNumber = (a, b) => Number(a.rule.slice(1)) - Number(b.rule.slice(1));
const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

/** The page for a list of `{ rule, says, check, status }` entries. */
export function render(checks) {
  const checked = checks.filter((entry) => entry.status === 'checked').sort(byNumber);
  const enforced = checks.filter((entry) => entry.status === 'enforced').sort(byNumber);
  const retired = checks.filter((entry) => entry.status === 'retired').sort(byNumber);
  const lines = [
    `<!-- Generated by \`${COMMAND}\` from web/scripts/design-checks.json; do not edit. -->`,
    '',
    '# Design checks',
    '',
    'What `npm run design:check` enforces, by rule in [the design rules](rules.md). Each failure',
    'prints what is wrong, the fix and the rule. Call sites awaiting a fix are listed in',
    '`web/scripts/design-rules-exemptions.json` and `web/scripts/composition-allowlist.json`,',
    'which only shrink.',
    '',
    '## Rules in the rulebook that a check helps enforce',
    '',
    '| Rule | Says | Checked by |',
    '| --- | --- | --- |',
    ...checked.map((e) => `| ${e.rule} | ${cell(e.says)} | ${cell(e.check)} |`),
  ];
  if (enforced.length > 0) {
    lines.push(
      '',
      '## Rules that live only in their check',
      '',
      'These left the rulebook because a check enforces them completely. The failure message',
      'says the fix.',
      '',
      '| Rule | Says | Checked by |',
      '| --- | --- | --- |',
      ...enforced.map((e) => `| ${e.rule} | ${cell(e.says)} | ${cell(e.check)} |`),
    );
  }
  if (retired.length > 0) {
    lines.push(
      '',
      '## Retired',
      '',
      'These numbers are not reused. Another rule, a primitive or a test covers each one now.',
      '',
      '| Rule | Said | Now covered by |',
      '| --- | --- | --- |',
      ...retired.map((e) => `| ${e.rule} | ${cell(e.says)} | ${cell(e.check)} |`),
    );
  }
  return `${lines.join('\n')}\n`;
}

export async function readChecks(webRoot) {
  return JSON.parse(await readFile(join(webRoot, 'scripts', 'design-checks.json'), 'utf8'));
}

/** Errors when the page differs from what the list generates. */
export async function checkPage(webRoot) {
  const expected = render(await readChecks(webRoot));
  let actual = null;
  try {
    actual = await readFile(join(webRoot, '..', PAGE), 'utf8');
  } catch {
    // Reported below.
  }
  return actual === expected
    ? []
    : [`${PAGE} is not current. Fix: run \`${COMMAND}\` and commit the page. ${cite('R6')}`];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  if (process.argv.includes('--check')) {
    const errors = await checkPage(webRoot);
    if (errors.length > 0) {
      console.error(errors.join('\n'));
      process.exit(1);
    }
  } else {
    await writeFile(join(webRoot, '..', PAGE), render(await readChecks(webRoot)));
    console.log(`Wrote ${PAGE}.`);
  }
}
